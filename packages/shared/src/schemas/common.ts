import { z } from 'zod';
import { EntityType } from '../constants/enums';

const REQUIRED = 'This field is required.';

/**
 * Validation messages are shown to people, in forms and in API error envelopes. Zod's defaults
 * describe the schema ("Invalid option: expected one of "A"|"B"…"); these describe what to do.
 * A message given on a schema itself still takes precedence.
 */
z.config({
  customError: (issue) => {
    const missing = issue.input === undefined || issue.input === null || issue.input === '';
    switch (issue.code) {
      case 'invalid_value':
        return missing ? 'Choose an option.' : 'Choose one of the listed options.';
      case 'invalid_type':
        return missing ? REQUIRED : undefined;
      case 'too_small':
        return issue.origin === 'string' && issue.minimum === 1 ? REQUIRED : undefined;
      case 'invalid_format':
        if (missing) return REQUIRED;
        return issue.format === 'email' ? 'Enter a valid email address.' : undefined;
      default:
        return undefined;
    }
  },
});

/** Database identifiers are cuid2-style strings generated by Prisma. */
export const Id = z.string({ error: REQUIRED }).min(1, REQUIRED).max(64);
/**
 * An optional identifier. A form `<select>` with nothing chosen submits an empty string, which
 * means "none", not an invalid id.
 */
export const optionalId = z.union([z.literal('').transform(() => undefined), Id]).optional();

/** Required trimmed text. */
export const text = (max: number) =>
  z.string({ error: REQUIRED }).trim().min(1, REQUIRED).max(max, `Use ${max} characters or fewer.`);
/** Optional trimmed text; an empty string becomes undefined. */
export const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max)
    .optional()
    .transform((v) => (v === '' ? undefined : v));
const INVALID_DATE = 'Enter a valid date.';
/**
 * A date sent as an ISO string (or a `YYYY-MM-DD` form value). Only strings and Date objects are
 * accepted: plain coercion would turn `null`, `true` or a stray number into a 1970 timestamp.
 */
export const date = z
  .union([z.string().trim().min(1), z.date()], { error: INVALID_DATE })
  .pipe(z.coerce.date({ error: INVALID_DATE }));
/** An optional date; an empty form value means "not set". */
export const optionalDate = z.union([z.literal('').transform(() => undefined), date]).optional();

const numeric = (message: string) =>
  z
    .union([z.number(), z.string().trim().min(1, message)], { error: message })
    .pipe(z.coerce.number({ error: message }));
/** A whole number from a form or JSON. An empty input is an error, never a silent 0. */
export const wholeNumber = (min: number, max: number, message = 'Enter a number.') =>
  numeric(message).pipe(
    z
      .number()
      .int('Use a whole number.')
      .min(min, `Must be at least ${min}.`)
      .max(max, `Must be at most ${max.toLocaleString('en-IN')}.`),
  );
/** Whole rupees. An empty input is an error, never a silent ₹0. */
export const rupees = (min = 0) => wholeNumber(min, 100_000_000, 'Enter an amount.');

export const IsoDate = z.iso.datetime({ offset: true });

export const PageQuery = z.object({
  cursor: z.string().optional(),
  limit: z.coerce.number().int().min(1).max(100).default(30),
});
export type PageQuery = z.infer<typeof PageQuery>;

export const SortDirection = z.enum(['asc', 'desc']);

export const EntityRef = z.object({ type: EntityType, id: Id });
export type EntityRef = z.infer<typeof EntityRef>;

/** Error envelope returned by every failing API request. */
export const ApiError = z.object({
  error: z.object({
    code: z.string(),
    message: z.string(),
    details: z.unknown().optional(),
    requestId: z.string().optional(),
  }),
});
export type ApiError = z.infer<typeof ApiError>;

export interface Page<T> {
  items: T[];
  nextCursor: string | null;
}
