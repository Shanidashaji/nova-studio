'use client';

import type { FinanceSummary } from '@nova/shared';
import { Info } from 'lucide-react';
import { useState } from 'react';
import {
  Bar,
  BarChart,
  CartesianGrid,
  Legend,
  ReferenceLine,
  ResponsiveContainer,
  Scatter,
  ScatterChart,
  Tooltip as RTooltip,
  XAxis,
  YAxis,
  ZAxis,
  LabelList,
} from 'recharts';
import { Badge } from '@/components/ui/badge';
import { Segmented } from '@/components/ui/misc';
import { Panel, PanelState } from '@/components/ui/panel';
import { useFocusFilter } from '@/features/shell/use-focus';
import { useCan } from '@/features/shell/user-context';
import { money, pct, titleCase } from '@/lib/format';
import { useFinance } from '@/lib/queries';
import { useWorkspace } from '@/store/workspace';

const axis = {
  stroke: 'var(--line-strong)',
  fontSize: 11,
  tick: { fill: 'var(--text-3)' },
  tickLine: false,
};
const grid = { stroke: 'var(--line)', strokeDasharray: '0', vertical: false };
const tooltipStyle = {
  contentStyle: {
    background: 'var(--surface-2)',
    border: '1px solid var(--line-strong)',
    borderRadius: 8,
    fontSize: 12,
    color: 'var(--text)',
  },
  labelStyle: { color: 'var(--text-2)' },
  itemStyle: { color: 'var(--text)' },
  cursor: { fill: 'var(--surface-3)', opacity: 0.5 },
};
const monthLabel = (m: string) =>
  new Date(`${m}-01T00:00:00`).toLocaleDateString('en-IN', { month: 'short' });

/** Business performance over DEMONSTRATION data — clearly marked as such. */
export function BusinessLens() {
  const canRead = useCan('finance:read');
  const q = useFinance(canRead);

  if (!canRead) {
    return <p className="text-sm text-text-2">Your role does not include access to finance.</p>;
  }

  return (
    <div className="flex flex-col gap-4">
      <div
        role="note"
        className="flex items-center gap-2 rounded-[var(--radius-md)] border border-attention-line bg-attention-soft px-3 py-2 text-sm text-attention"
      >
        <Info className="size-4 shrink-0" />
        Demonstration data. These figures are generated by the seed and are not Neon Minds’ real
        finances.
      </div>
      <PanelState query={q} skeleton="chart">
        {q.data ? <BusinessContent data={q.data} /> : null}
      </PanelState>
    </div>
  );
}

function BusinessContent({ data }: { data: FinanceSummary }) {
  const { focus, matchesProjectId } = useFocusFilter();
  const projects = data.projects.filter((p) => matchesProjectId(p.id));
  const income = data.totals.income;
  const expenses = data.totals.expenses;

  return (
    <div className="grid grid-cols-1 gap-4 xl:grid-cols-12">
      <section
        aria-label="Six-month totals"
        className="grid grid-cols-3 overflow-hidden rounded-[var(--radius-md)] border border-line bg-surface-1 xl:col-span-12"
      >
        {[
          { label: 'Income · 6 months', value: money(income) },
          { label: 'Expenses · 6 months', value: money(expenses) },
          { label: 'Margin', value: `${data.totals.margin}%` },
        ].map((t) => (
          <div key={t.label} className="border-r border-line px-4 py-3 last:border-r-0">
            <p className="eyebrow">{t.label}</p>
            <p className="font-mono text-2xl tabular text-text">{t.value}</p>
          </div>
        ))}
      </section>
      <MonthlyChart data={data} className="xl:col-span-7" />
      <CategoryChart data={data} className="xl:col-span-5" />
      <BurnChart projects={projects} focused={focus !== null} className="xl:col-span-12" />
    </div>
  );
}

function ViewToggle({
  value,
  onChange,
}: {
  value: 'chart' | 'table';
  onChange: (v: 'chart' | 'table') => void;
}) {
  return (
    <Segmented
      label="Display"
      value={value}
      onChange={onChange}
      options={[
        { value: 'chart', label: 'Chart' },
        { value: 'table', label: 'Table' },
      ]}
    />
  );
}

function MonthlyChart({ data, className }: { data: FinanceSummary; className?: string }) {
  const [view, setView] = useState<'chart' | 'table'>('chart');
  const rows = data.months.map((m) => ({ ...m, label: monthLabel(m.month) }));
  return (
    <Panel
      eyebrow="Studio-wide · monthly"
      title="Income and expenses"
      className={className}
      action={<ViewToggle value={view} onChange={setView} />}
    >
      {view === 'chart' ? (
        <div
          className="h-64"
          role="img"
          aria-label="Monthly income and expenses for the last six months"
        >
          <ResponsiveContainer width="100%" height="100%">
            <BarChart
              data={rows}
              barGap={2}
              barCategoryGap="28%"
              margin={{ top: 8, right: 4, left: 0, bottom: 0 }}
            >
              <CartesianGrid {...grid} />
              <XAxis dataKey="label" {...axis} />
              <YAxis
                {...axis}
                width={48}
                tickFormatter={(v: number) => money(v)}
                axisLine={false}
              />
              <RTooltip {...tooltipStyle} formatter={(v) => money(Number(v), { exact: true })} />
              <Legend
                iconType="circle"
                iconSize={8}
                wrapperStyle={{ fontSize: 12, color: 'var(--text-2)' }}
              />
              <Bar dataKey="income" name="Income" fill="var(--cat-1)" radius={[4, 4, 0, 0]} />
              <Bar dataKey="expenses" name="Expenses" fill="var(--cat-2)" radius={[4, 4, 0, 0]} />
            </BarChart>
          </ResponsiveContainer>
        </div>
      ) : (
        <SimpleTable
          head={['Month', 'Income', 'Expenses', 'Net']}
          rows={rows.map((r) => [
            r.label,
            money(r.income, { exact: true }),
            money(r.expenses, { exact: true }),
            money(r.income - r.expenses, { exact: true }),
          ])}
        />
      )}
    </Panel>
  );
}

function CategoryChart({ data, className }: { data: FinanceSummary; className?: string }) {
  const [view, setView] = useState<'chart' | 'table'>('chart');
  const rows = data.byCategory
    .filter((c) => c.kind === 'EXPENSE')
    .map((c) => ({ name: titleCase(c.category), amount: c.amount }));
  return (
    <Panel
      eyebrow="Studio-wide · 6 months"
      title="Where the money goes"
      className={className}
      action={<ViewToggle value={view} onChange={setView} />}
    >
      {view === 'chart' ? (
        <div className="h-64" role="img" aria-label="Expenses by category">
          <ResponsiveContainer width="100%" height="100%">
            <BarChart
              data={rows}
              layout="vertical"
              margin={{ top: 0, right: 56, left: 0, bottom: 0 }}
              barCategoryGap={4}
            >
              <XAxis type="number" hide />
              <YAxis type="category" dataKey="name" {...axis} width={112} axisLine={false} />
              <RTooltip {...tooltipStyle} formatter={(v) => money(Number(v), { exact: true })} />
              <Bar dataKey="amount" name="Expenses" fill="var(--cat-2)" radius={[0, 4, 4, 0]}>
                <LabelList
                  dataKey="amount"
                  position="right"
                  formatter={(v) => money(Number(v))}
                  style={{ fill: 'var(--text-2)', fontSize: 11 }}
                />
              </Bar>
            </BarChart>
          </ResponsiveContainer>
        </div>
      ) : (
        <SimpleTable
          head={['Category', 'Amount']}
          rows={rows.map((r) => [r.name, money(r.amount, { exact: true })])}
        />
      )}
    </Panel>
  );
}

/**
 * Budget burn against progress: each production is a point; the diagonal is "spending in step
 * with progress". Points well above it are burning budget faster than they deliver.
 */
function BurnChart({
  projects,
  focused,
  className,
}: {
  projects: FinanceSummary['projects'];
  focused: boolean;
  className?: string;
}) {
  const [view, setView] = useState<'chart' | 'table'>('chart');
  const inspect = useWorkspace((s) => s.inspect);
  const points = projects.map((p) => ({
    id: p.id,
    title: p.title,
    x: Math.round(p.progress * 100),
    y: p.budget ? Math.round((p.spent / p.budget) * 100) : 0,
    flag: p.burnVsProgress > 0.15 ? p.title : '',
    budget: p.budget,
    spent: p.spent,
  }));

  return (
    <Panel
      eyebrow={focused ? 'Productions in focus' : 'Per production'}
      title="Budget burn vs progress"
      className={className}
      action={<ViewToggle value={view} onChange={setView} />}
    >
      <p className="mb-2 text-xs text-text-3">
        Above the diagonal = spending faster than work is completed. Labelled points exceed it by
        more than 15 points (NOVA estimate).
      </p>
      {view === 'chart' ? (
        <div
          className="h-72"
          role="img"
          aria-label="Scatter plot of budget used against progress for each production"
        >
          <ResponsiveContainer width="100%" height="100%">
            <ScatterChart margin={{ top: 12, right: 24, left: 0, bottom: 8 }}>
              <CartesianGrid stroke="var(--line)" />
              <XAxis
                type="number"
                dataKey="x"
                name="Progress"
                unit="%"
                domain={[0, 100]}
                {...axis}
              />
              <YAxis
                type="number"
                dataKey="y"
                name="Budget used"
                unit="%"
                domain={[0, 100]}
                {...axis}
                width={44}
              />
              <ZAxis range={[90, 90]} />
              <ReferenceLine
                segment={[
                  { x: 0, y: 0 },
                  { x: 100, y: 100 },
                ]}
                stroke="var(--text-3)"
                strokeDasharray="4 4"
                ifOverflow="extendDomain"
              />
              <RTooltip
                {...tooltipStyle}
                cursor={{ strokeDasharray: '3 3', stroke: 'var(--line-strong)' }}
                content={({ payload }) => {
                  const p = payload?.[0]?.payload as (typeof points)[number] | undefined;
                  if (!p) return null;
                  return (
                    <div className="rounded-lg border border-line-strong bg-surface-2 px-2.5 py-1.5 text-xs shadow-[var(--shadow-float)]">
                      <p className="font-medium text-text">{p.title}</p>
                      <p className="text-text-2">
                        {p.x}% done · {p.y}% of budget ({money(p.spent)} / {money(p.budget)})
                      </p>
                    </div>
                  );
                }}
              />
              <Scatter
                data={points}
                fill="var(--cat-1)"
                stroke="var(--surface-1)"
                strokeWidth={2}
                cursor="pointer"
                onClick={(d: { payload?: { id: string } }) =>
                  d.payload && inspect({ type: 'project', id: d.payload.id })
                }
              >
                <LabelList
                  dataKey="flag"
                  position="top"
                  style={{ fill: 'var(--text-2)', fontSize: 11 }}
                />
              </Scatter>
            </ScatterChart>
          </ResponsiveContainer>
        </div>
      ) : (
        <SimpleTable
          head={['Production', 'Progress', 'Budget used', 'Spent', 'Budget']}
          rows={projects.map((p) => [
            p.title,
            pct(p.progress),
            p.budget ? pct(p.spent / p.budget) : '—',
            money(p.spent, { exact: true }),
            money(p.budget, { exact: true }),
          ])}
        />
      )}
      {projects.some((p) => p.burnVsProgress > 0.15) ? (
        <div className="mt-2 flex flex-wrap gap-2">
          {projects
            .filter((p) => p.burnVsProgress > 0.15)
            .map((p) => (
              <button
                key={p.id}
                type="button"
                onClick={() => inspect({ type: 'project', id: p.id, section: 'budget' })}
              >
                <Badge tone="attention">
                  {p.title}: {pct(p.spent / p.budget)} spent at {pct(p.progress)} done
                </Badge>
              </button>
            ))}
        </div>
      ) : null}
    </Panel>
  );
}

function SimpleTable({ head, rows }: { head: string[]; rows: string[][] }) {
  return (
    <div className="overflow-x-auto">
      <table className="w-full text-sm">
        <thead>
          <tr>
            {head.map((h) => (
              <th key={h} scope="col" className="eyebrow py-1.5 pr-4 text-left font-medium">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((r) => (
            <tr key={r[0]} className="border-t border-line/60">
              {r.map((c, i) => (
                <td
                  key={i}
                  className={
                    i === 0 ? 'py-1.5 pr-4 text-text' : 'py-1.5 pr-4 font-mono text-xs text-text-2'
                  }
                >
                  {c}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
